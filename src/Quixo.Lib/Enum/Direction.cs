namespace Quixo.Lib.Enum
{
    /// <summary>
    /// Represents the possible movement directions on the board.
    /// </summary>
    public enum Direction
    {
        /// <summary>
        /// Movement upward.
        /// </summary>
        UP,

        /// <summary>
        /// Movement downward.
        /// </summary>
        DOWN,

        /// <summary>
        /// Movement to the right.
        /// </summary>
        RIGHT,

        /// <summary>
        /// Movement to the left.
        /// </summary>
        LEFT
    }
}